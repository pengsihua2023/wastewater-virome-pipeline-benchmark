#!/usr/bin/env python3
"""Convert the platform-specific and combined manuscripts from Markdown to .docx.

Reuses the Markdown->docx renderer from 12_traceability_and_docx.py so both
documents share formatting with the combined manuscript, then appends that
platform's six figures (generated by 17_platform_figures.py).
"""
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "analysis_708" / "scripts"

TARGETS = [
    ("Seven-pipleline-comparison-on-Illumina.md",
     "Seven-pipleline-comparison-on-Illumina.docx", "figures_illumina"),
    ("Seven-pipleline-comparison-on-Pacbio.md",
     "Seven-pipleline-comparison-on-Pacbio.docx", "figures_pacbio"),
    ("Seven-pipeline-comparison-combined.md",
     "Seven-pipeline-comparison-combined.docx", "figures_combined"),
]


def load_renderer():
    spec = importlib.util.spec_from_file_location(
        "trace_docx", SCRIPTS / "12_traceability_and_docx.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    mod = load_renderer()
    rc = 0
    for md_name, docx_name, figdir in TARGETS:
        md = ROOT / md_name
        out = ROOT / docx_name
        figs = ROOT / "analysis_708" / figdir
        if not md.exists():
            print(f"MISSING {md}")
            rc = 1
            continue
        if not figs.is_dir():
            print(f"MISSING figure directory {figs} - run 17_platform_figures.py first")
            rc = 1
            continue
        n = len(sorted(figs.glob("Figure*.png")))
        try:
            mod.md_to_docx(md, out, figs)
            print(f"        embedded {n} figures from {figdir}/")
        except PermissionError:
            print(f"LOCKED  {out} is open in Word - close it and re-run")
            rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main())
